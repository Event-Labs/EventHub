/**
 * Translates address string into English and deduplicates redundant city/district parts.
 */
export function translateAddress(addr) {
  if (!addr || typeof addr !== 'string') return addr
  let res = addr.trim()
  if (!res) return addr

  // 1. City & Province names FIRST (prevent accidental partial word collisions)
  res = res.replace(/(?:Thành\s*phố|TP\.?)\s*Hồ\s*Chí\s*Minh/gui, 'Ho Chi Minh City')
  res = res.replace(/(?:Thành\s*phố|TP\.?)\s*Hà\s*Nội/gui, 'Hanoi')
  res = res.replace(/(?:Thành\s*phố|TP\.?)\s*Đà\s*Nẵng/gui, 'Da Nang')
  res = res.replace(/(?:Thành\s*phố|TP\.?)\s*Thủ\s*Đức/gui, 'Thu Duc City')
  res = res.replace(/(?:Thành\s*phố|TP\.?)\s*Hải\s*Phòng/gui, 'Hai Phong')
  res = res.replace(/(?:Thành\s*phố|TP\.?)\s*Cần\s*Thơ/gui, 'Can Tho')
  res = res.replace(/(?:Thành\s*phố|TP\.?)\s*Nha\s*Trang/gui, 'Nha Trang')
  res = res.replace(/(?:Thành\s*phố|TP\.?)\s*Huế/gui, 'Hue')
  res = res.replace(/(?:Thành\s*phố|TP\.?)\s*Vũng\s*Tàu/gui, 'Vung Tau')
  res = res.replace(/Tỉnh\s+Hưng\s+Yên/gui, 'Hung Yen Province')
  res = res.replace(/Tỉnh\s+Bình\s+Dương/gui, 'Binh Duong Province')
  res = res.replace(/Tỉnh\s+Đồng\s+Nai/gui, 'Dong Nai Province')
  res = res.replace(/Tỉnh\s+Bà\s+Rịa\s*[-–]\s*Vũng\s+Tàu/gui, 'Ba Ria - Vung Tau Province')
  res = res.replace(/(^|[^\p{L}\p{N}])Hà\s*Nội(?=[^\p{L}\p{N}]|$)/gui, '$1Hanoi')
  res = res.replace(/(^|[^\p{L}\p{N}])Đà\s*Nẵng(?=[^\p{L}\p{N}]|$)/gui, '$1Da Nang')
  res = res.replace(/(^|[^\p{L}\p{N}])Việt\s*Nam(?=[^\p{L}\p{N}]|$)/gui, '$1Vietnam')

  // 2. Specific compound terms
  res = res.replace(/Khu\s+phố\s+cổ/gui, 'Old Quarter')
  res = res.replace(/Khu\s+phố\s+(\d+)/gui, 'Quarter $1')
  res = res.replace(/Khu\s+phố\s+([^,]+)/gui, '$1 Quarter')

  // 3. Known venues
  const VENUES = {
    "Lá Nhà Garden": "La Nha Garden",
    "Nhà hát Kịch Sân Khấu Nhỏ": "Small Stage Drama Theatre",
    "Nhà hát Kịch Sân Khấu Nhỏ": "Small Stage Drama Theatre",
    "Sân khấu Kịch 5B": "5B Drama Stage",
    "Sân khấu 5B": "5B Stage",
    "Nhà hát Bến Thành": "Ben Thanh Theatre",
    "Nhà hát Hòa Bình": "Hoa Binh Theatre",
    "Cung Điền Kinh Mỹ Đình": "My Dinh Athletics Palace",
    "Cung Thể Thao Điền Kinh Mỹ Đình": "My Dinh Athletics Sports Palace",
    "Sân Khấu Quốc Thảo": "Quoc Thao Stage",
    "Sân khấu Quốc Thảo": "Quoc Thao Stage",
    "Công viên APEC": "APEC Park",
    "Nhà Hát Trưng Vương": "Trung Vuong Theatre",
    "Nhà hát Trưng Vương": "Trung Vuong Theatre",
    "Nhà hát Trần Hữu Trang": "Tran Huu Trang Theatre",
    "Nhà Hát Kịch IDECAF": "IDECAF Drama Theatre",
    "Nhà Hát Của Những Ước Mơ": "Theatre of Dreams",
    "Nhà Đạt": "Dat's House",
    "Bãi biển Thanh Khê": "Thanh Khe Beach",
    "Trung tâm Triển lãm VEC": "VEC Exhibition Center",
    "Sự kiện ngoài trời": "Outdoor Event",
    "Kịch Phú Nhuận": "Phu Nhuan Drama Stage",
    "Uỷ ban nhân dân thành phố Hà Nội": "Hanoi People's Committee",
    "Trường Tiểu học Trưng Vương": "Trung Vuong Primary School"
  }

  for (const [vi, en] of Object.entries(VENUES)) {
    res = res.split(vi).join(en)
  }

  // 4. Street, Alley, Ward, District with Unicode boundary
  res = res.replace(/(?:^|[^\p{L}\p{N}])Hẻm\s+(\S+)\s*(?:Đường\s+)?([^,]+)/gui, 'Alley $1, $2 Street')
  res = res.replace(/(?:^|[^\p{L}\p{N}])Hẻm\s+(\S+)/gui, 'Alley $1')
  res = res.replace(/(?:^|[^\p{L}\p{N}])Ngõ\s+(\S+)/gui, 'Lane $1')
  res = res.replace(/(?:^|[^\p{L}\p{N}])Ngách\s+(\S+)/gui, 'Alley $1')
  res = res.replace(/(^|\s)(?:Đường|Phố)\s+([^,]+)/gui, (m, sp, street) => `${sp}${street.trim()} Street`)
  res = res.replace(/(?:^|[^\p{L}\p{N}])Phường\s+(\d+)/gui, 'Ward $1')
  res = res.replace(/(?:^|[^\p{L}\p{N}])Phường\s+([^,]+)/gui, (m, p1) => `${p1.trim()} Ward`)
  res = res.replace(/(?:^|[^\p{L}\p{N}])Quận\s+(\d+)/gui, 'District $1')
  res = res.replace(/(?:^|[^\p{L}\p{N}])Quận\s+([^,]+)/gui, (m, p1) => `${p1.trim()} District`)
  res = res.replace(/(?:^|[^\p{L}\p{N}])Huyện\s+([^,]+)/gui, (m, p1) => `${p1.trim()} District`)
  res = res.replace(/(?:^|[^\p{L}\p{N}])Thị\s*xã\s+([^,]+)/gui, (m, p1) => `${p1.trim()} Town`)
  res = res.replace(/(?:^|[^\p{L}\p{N}])Xã\s+([^,]+)/gui, (m, p1) => `${p1.trim()} Commune`)
  res = res.replace(/(?:^|[^\p{L}\p{N}])Tỉnh\s+([^,]+)/gui, (m, p1) => `${p1.trim()} Province`)
  res = res.replace(/(?:^|[^\p{L}\p{N}])Lầu\s+(\d+)/gui, 'Floor $1')
  res = res.replace(/(?:^|[^\p{L}\p{N}])Tầng\s+(\d+)/gui, 'Floor $1')
  res = res.replace(/(?:^|[^\p{L}\p{N}])Số\s+(\d+)/gui, 'No. $1')

  // 5. Clean up duplicate parts and trim
  const parts = res.split(',').map((p) => p.trim()).filter(Boolean)
  const seen = new Set()
  const deduped = []
  for (const part of parts) {
    const lower = part.toLowerCase()
    if (!seen.has(lower)) {
      seen.add(lower)
      deduped.push(part)
    }
  }

  return deduped.join(', ')
}

/**
 * Clean and format venue details with deduplication and English translation support.
 */
export function cleanAndFormatVenue(venue, isEnglish = false) {
  if (!venue) return isEnglish ? 'Venue to be announced' : 'Địa điểm cập nhật sau'
  if (typeof venue === 'string') {
    return isEnglish ? translateAddress(venue) : venue
  }
  const name = venue.name || ''
  const addr = venue.address_line || ''
  const ward = venue.ward || ''
  const district = venue.district || ''
  const city = venue.city || ''

  const parts = []
  if (name) parts.push(name)
  if (addr) parts.push(addr)
  if (ward && !parts.some((p) => p.toLowerCase().includes(ward.toLowerCase()))) parts.push(ward)
  if (district && !parts.some((p) => p.toLowerCase().includes(district.toLowerCase()))) parts.push(district)
  if (city && !parts.some((p) => p.toLowerCase().includes(city.toLowerCase()))) parts.push(city)

  const joined = parts.join(', ')
  return isEnglish ? translateAddress(joined) : joined
}

/**
 * Translates HTML description content when English is active.
 */
export function translateEventHtmlDescription(html, isEnglish = false) {
  if (!html || typeof html !== 'string') return ''
  let cleaned = html
    .replace(/&nbsp;/gi, ' ')
    .replace(/\u00A0/g, ' ')

  if (!isEnglish) return cleaned

  for (const [vi, en] of Object.entries(EVENT_SYSTEM_TRANSLATIONS)) {
    if (vi.length > 5 && cleaned.includes(vi)) {
      cleaned = cleaned.split(vi).join(en)
    }
  }

  return cleaned
}

/**
 * Translates event title if an official English translation is available.
 */
export function translateEventTitle(title, isEnglish = false) {
  if (!title || typeof title !== 'string' || !isEnglish) return title
  const trimmed = title.trim()
  if (EVENT_SYSTEM_TRANSLATIONS[trimmed]) return EVENT_SYSTEM_TRANSLATIONS[trimmed]
  const lower = trimmed.toLowerCase()
  for (const [k, v] of Object.entries(EVENT_SYSTEM_TRANSLATIONS)) {
    if (k.toLowerCase() === lower) return v
  }
  return title
}
